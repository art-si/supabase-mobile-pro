import { readFile, readdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = resolve(import.meta.dirname, '..')
const core = resolve(root, 'packages/mobile-core')
const fonts = resolve(core, 'assets/fonts')
const fontPath = resolve(fonts, 'tms-sans-sc.woff2')
const applications = [
  'supabase-mobile-tms-driver',
  'supabase-mobile-tms-shipper',
  'supabase-mobile-smis'
]
const excludedDirectories = new Set(['assets', 'static', '_mobile-core'])
const require = createRequire(import.meta.url)

async function collectSourceHan(directory, characters) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) {
      if (!excludedDirectories.has(entry.name)) await collectSourceHan(path, characters)
    } else if (/\.(vue|ts|scss|json)$/.test(entry.name)) {
      const text = await readFile(path, 'utf8')
      for (const character of text.match(/\p{Script=Han}/gu) ?? []) characters.add(character)
    }
  }
}

export async function buildUiFont(sourcePath) {
  if (sourcePath) {
    const subsetFont = require('subset-font')
    const characters = new Set(await readFile(resolve(fonts, 'common-han.txt'), 'utf8'))
    for (let code = 32; code <= 126; code++) characters.add(String.fromCharCode(code))
    for (const character of '，。！？：；（）【】《》、·—…％℃㎡³¥￥✓×→←↑↓‐－　“”‘’•①②③') characters.add(character)
    for (const application of applications) {
      await collectSourceHan(resolve(root, 'modules', application, 'src'), characters)
    }
    await collectSourceHan(resolve(core, 'src'), characters)

    const source = await readFile(resolve(sourcePath))
    const subset = await subsetFont(source, [...characters].join(''), {
      targetFormat: 'woff2',
      variationAxes: { wght: { min: 400, max: 700 } }
    })
    await writeFile(fontPath, subset)
    console.log(`Subset ${characters.size} UI characters`)
  }

  const font = await readFile(fontPath)
  const css = `// Generated by pnpm font:css. See assets/fonts/NotoSansSC-OFL.txt.
@mixin embed() {
  @font-face {
    font-family: 'TMS Sans SC';
    src: url('data:font/woff2;base64,${font.toString('base64')}') format('woff2');
    font-style: normal;
    font-weight: 400 700;
    font-display: swap;
  }
}
`
  await writeFile(resolve(core, 'src/styles/font.scss'), css)
  console.log(`Embedded ${font.byteLength} byte UI font`)
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await buildUiFont(process.argv[2])
}
