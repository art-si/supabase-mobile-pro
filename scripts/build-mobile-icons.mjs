import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = resolve(import.meta.dirname, '..')
const core = resolve(root, 'packages/mobile-core')
const driver = resolve(root, 'modules/supabase-mobile-tms-driver')

export async function buildMobileIcons(applicationRoot = driver) {
  const fromApplication = createRequire(resolve(applicationRoot, 'package.json'))
  const subsetFont = fromApplication('subset-font')
  const [manifestText, css, font] = await Promise.all([
    readFile(resolve(core, 'assets/fonts/icon-manifest.json'), 'utf8'),
    readFile(fromApplication.resolve('bootstrap-icons/font/bootstrap-icons.css'), 'utf8'),
    readFile(fromApplication.resolve('bootstrap-icons/font/fonts/bootstrap-icons.woff2'))
  ])
  const iconCodes = new Map([...css.matchAll(/\.bi-([\w-]+)::before\s*\{\s*content:\s*"\\([0-9a-f]+)";/g)]
    .map(([, name, code]) => [name, Number.parseInt(code, 16)]))
  const glyphs = Object.entries(JSON.parse(manifestText)).map(([name, source]) => {
    const code = iconCodes.get(source)
    if (code === undefined) throw new Error(`Unknown Bootstrap icon: ${source} (${name})`)
    return [name, code]
  })
  const characters = [...new Set(glyphs.map(([, code]) => String.fromCodePoint(code)))].join('')
  const subset = await subsetFont(font, characters, { targetFormat: 'sfnt' })
  if (subset.byteLength >= 40 * 1024) {
    throw new Error(`Icon font must stay below the Uni-app local font limit: ${subset.byteLength} bytes`)
  }

  const generated = '// Generated by pnpm icons:build from assets/fonts/icon-manifest.json and Bootstrap Icons.'
  const types = [
    generated,
    'export const iconGlyphs = {',
    ...glyphs.map(([name, code]) => `  ${JSON.stringify(name)}: '\\u{${code.toString(16)}}',`),
    '} as const',
    '',
    'export type MobileIconName = keyof typeof iconGlyphs',
    ''
  ].join('\n')
  const styles = `${generated}
@mixin embed() {
  @font-face {
    font-family: 'Mobile Pro Icons';
    src: url('data:font/ttf;base64,${subset.toString('base64')}') format('truetype');
    font-style: normal;
    font-weight: 400;
    font-display: block;
  }
}
`
  await Promise.all([
    writeFile(resolve(core, 'src/icons.ts'), types),
    writeFile(resolve(core, 'src/styles/icons.scss'), styles)
  ])
  console.log(`Built ${characters.length} shared icons, ${subset.byteLength} byte font`)
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await buildMobileIcons()
}
